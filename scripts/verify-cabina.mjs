import assert from 'node:assert/strict';
import http from 'node:http';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import WebSocket from 'ws';
const require=createRequire(import.meta.url),{createCabina}=require('../server/cabina.cjs');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../public');
const hub=createCabina({root,ackTimeout:250});
const server=http.createServer(async(req,res)=>{if(!await hub.http(req,res)){res.statusCode=404;res.end();}});
server.on('upgrade',hub.upgrade);
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const origin=`http://127.0.0.1:${server.address().port}`,url=origin.replace('http','ws')+'/cabina-ws';
const connections=[];
function connect(join){return new Promise((resolve,reject)=>{
 const ws=new WebSocket(url,{origin}),messages=[],waiters=[];connections.push(ws);
 ws.on('error',reject);
 const client={ws,messages,send:m=>ws.send(JSON.stringify(m)),wait:(predicate)=>{
  const index=messages.findIndex(predicate);if(index>=0)return Promise.resolve(messages.splice(index,1)[0]);
  return new Promise((ok,bad)=>{const waiter={predicate,ok,timer:setTimeout(()=>{const i=waiters.indexOf(waiter);if(i>=0)waiters.splice(i,1);bad(new Error('Sin respuesta de la sala'));},1500)};waiters.push(waiter);});
 }};
 ws.on('message',raw=>{const message=JSON.parse(raw);const index=waiters.findIndex(w=>w.predicate(message));if(index>=0){const w=waiters.splice(index,1)[0];clearTimeout(w.timer);w.ok(message);}else messages.push(message);});
 ws.on('open',()=>{client.send({type:'join',...join});resolve(client);});
});}
const command=(c,id,action,extra={})=>c.send({type:'command',id,action,epoch:hub.room().epoch,...extra});
try{
 const bootstrap=await fetch(origin+'/api/cabina/bootstrap').then(r=>r.json());
 const content=await fetch(origin+`/api/cabina/content?room=${bootstrap.code}`).then(r=>r.json());
 assert.equal(content.slides.length,22);assert.equal(Object.keys(content.scripts).length,22);
 assert.equal((await fetch(origin+'/api/cabina/content?room=wrong')).status,403);
 assert.equal((await fetch(origin+'/api/cabina/close',{method:'POST'})).status,403);
 const invalid=await connect({role:'controller',code:'wrong',name:'Davis'});
 assert.match((await invalid.wait(m=>m.type==='error')).message,/código/i);
 const stage=await connect({role:'stage',token:bootstrap.hostToken});await stage.wait(m=>m.type==='welcome');
 stage.send({type:'stage.ready',state:hub.room().state});await stage.wait(m=>m.type==='room'&&m.room.stageReady);
 const davis=await connect({role:'controller',code:bootstrap.code,name:'Davis'});const d=await davis.wait(m=>m.type==='welcome');
 const haroldo=await connect({role:'controller',code:bootstrap.code,name:'Haroldo'});await haroldo.wait(m=>m.type==='welcome');
 const juan=await connect({role:'controller',code:bootstrap.code,name:'Juan Carlos'});await juan.wait(m=>m.type==='welcome');
 assert.equal(hub.room().presence.length,3);
 command(haroldo,'denied','slide.nextStep');assert.match((await haroldo.wait(m=>m.id==='denied')).message,/Davis/);
 command(davis,'invalid-progress','model.progress',{value:2});assert.match((await davis.wait(m=>m.id==='invalid-progress')).message,/admitida/);
 command(davis,'unconfirmed','mode.set',{value:'shared'});assert.match((await davis.wait(m=>m.id==='unconfirmed')).message,/confirmar/);
 assert.equal(hub.room().mode,'individual');
 command(davis,'shared','mode.set',{value:'shared',confirmed:true});await davis.wait(m=>m.id==='shared');assert.equal(hub.room().mode,'shared');
 command(haroldo,'first','slide.nextStep');const action=await stage.wait(m=>m.type==='execute'&&m.command.id==='first');assert.equal(action.command.action,'slide.nextStep');
 command(juan,'busy','model.next');assert.match((await juan.wait(m=>m.id==='busy')).message,/Espera/);
 const state=structuredClone(hub.room().state);state.source='slide';state.reveal=1;
 stage.send({type:'stage.applied',id:'first',state});await haroldo.wait(m=>m.type==='ack'&&m.id==='first');assert.equal(hub.room().state.reveal,1);
 const revision=hub.room().revision;
 command(haroldo,'first','slide.nextStep');await haroldo.wait(m=>m.type==='ack'&&m.id==='first');assert.equal(hub.room().revision,revision,'Un reintento no debe repetir la orden');
 command(davis,'solo','mode.set',{value:'individual',confirmed:true});await davis.wait(m=>m.id==='solo');
 command(haroldo,'revoked','slide.nextStep');assert.match((await haroldo.wait(m=>m.id==='revoked')).message,/Davis/);
 command(davis,'handoff','turn.set',{value:'Haroldo',confirmed:true});await davis.wait(m=>m.id==='handoff');assert.equal(hub.room().owner,'Haroldo');
 command(davis,'old-owner','slide.nextStep');assert.match((await davis.wait(m=>m.id==='old-owner')).message,/Haroldo/);
 command(haroldo,'timeout','slide.nextStep');await stage.wait(m=>m.type==='execute'&&m.command.id==='timeout');assert.match((await haroldo.wait(m=>m.id==='timeout'&&m.type==='error')).message,/confirmó/);assert.equal(hub.room().busy,false);
 const resume=d.resumeToken;davis.ws.close();await new Promise(resolve=>davis.ws.once('close',resolve));
 const restored=await connect({role:'controller',code:bootstrap.code,name:'Davis',resumeToken:resume});const restoredWelcome=await restored.wait(m=>m.type==='welcome');assert.equal(restoredWelcome.clientId,d.clientId);assert.equal(restoredWelcome.room.state.reveal,1);
 const oldConnection=restoredWelcome.room.presence.find(p=>p.name==='Davis').connectionId;
 const takeover=await connect({role:'controller',code:bootstrap.code,name:'Davis',resumeToken:resume});const takeoverWelcome=await takeover.wait(m=>m.type==='welcome');
 assert.equal(takeoverWelcome.clientId,d.clientId);assert.notEqual(takeoverWelcome.room.presence.find(p=>p.name==='Davis').connectionId,oldConnection);
 assert.equal(takeoverWelcome.room.presence.filter(p=>p.name==='Davis').length,1,'Una recarga autorizada sustituye la conexión anterior');
 stage.ws.close();await new Promise(resolve=>stage.ws.once('close',resolve));
 command(haroldo,'offline','slide.nextStep');assert.match((await haroldo.wait(m=>m.id==='offline')).message,/salida/);
 assert.equal(hub.room().state.reveal,1,'No deben acumularse cambios sin una salida');
 console.log('PASS: sala con tres integrantes, acceso, 22 guiones, permisos, confirmación, cesión, orden, deduplicación, timeout y reconexión sin repetir pasos.');
}finally{for(const ws of connections)ws.terminate();hub.close();await new Promise(resolve=>server.close(resolve));}
